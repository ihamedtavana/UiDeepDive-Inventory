import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { App } from './App'
import { inventorySummary, readStockDeliveries } from './stockInventory'

beforeEach(() => {
  const stored = new Map<string, string>()
  vi.stubGlobal('localStorage', { getItem: (key: string) => stored.get(key) ?? null, setItem: (key: string, value: string) => stored.set(key, value) })
  vi.stubGlobal('matchMedia', (query: string) => ({ matches: query.includes('reduced-motion'), addEventListener() {}, removeEventListener() {} }))
  Object.defineProperty(HTMLDialogElement.prototype, 'showModal', { configurable: true, value(this: HTMLDialogElement) { this.open = true } })
  Object.defineProperty(HTMLDialogElement.prototype, 'close', { configurable: true, value(this: HTMLDialogElement) { this.open = false } })
})
afterEach(() => { cleanup(); vi.unstubAllGlobals() })

it('replaces the entire shelf grid, saves stock into the clicked bin, updates totals and restores inventory on Undo', async () => {
  render(<App />)
  fireEvent.click(screen.getByRole('button', { name: 'View Shelf A1' }))
  const shelf = within(screen.getByRole('region', { name: 'Shelf A1 · Graphics Cards' }))
  expect(screen.queryByRole('button', { name: 'View Shelf B1' })).toBeNull()
  expect(shelf.getAllByRole('button', { name: /Manage stock/ })).toHaveLength(12)
  expect(shelf.getByRole('status').textContent).toContain('186 of 288 units. 65%')
  const opener = shelf.getByRole('button', { name: /A1-L2-S3, GeForce RTX 4070 Super, 0 of 24/ })
  opener.focus()
  fireEvent.click(opener)
  const dialog = within(screen.getByRole('dialog', { name: 'Add stock' }))
  fireEvent.click(dialog.getByRole('button', { name: '+5' }))
  fireEvent.click(dialog.getByRole('button', { name: 'Add 5 units' }))
  await dialog.findByRole('heading', { name: '5 units added' })
  expect(shelf.getByRole('status').textContent).toContain('191 of 288 units. 66%')
  expect(within(opener).getByRole('img').getAttribute('aria-label')).toBe('Bin: 5 of 24 slots used')
  expect(inventorySummary(readStockDeliveries(), 'New York Central').used).toBe(1239)
  expect(screen.getByRole('button', { name: 'Out · 20' })).toBeTruthy()
  fireEvent.click(dialog.getByRole('button', { name: 'Undo' }))
  await dialog.findByRole('textbox', { name: 'Quantity to add' })
  expect(shelf.getByRole('status').textContent).toContain('186 of 288 units. 65%')
  expect(readStockDeliveries()).toEqual([])
  fireEvent(screen.getByRole('dialog', { name: 'Add stock' }), new Event('cancel', { cancelable: true }))
  expect(screen.queryByRole('dialog')).toBeNull()
  expect(document.activeElement).toBe(opener)
  fireEvent.click(shelf.getByRole('button', { name: 'All shelves' }))
  expect(screen.getAllByRole('button', { name: /View Shelf/ })).toHaveLength(8)
})

it('switches sections by keyboard and remembers the selected shelf in each section', async () => {
  render(<App />)
  fireEvent.click(screen.getByRole('button', { name: 'View Shelf A1' }))
  fireEvent.click(screen.getByRole('button', { name: 'A2' }))
  let trigger = screen.getByRole('button', { name: 'Section: Section A' })
  fireEvent.keyDown(trigger, { key: 'ArrowDown' })
  const a = screen.getByRole('option', { name: 'Section A' })
  fireEvent.keyDown(a, { key: 'ArrowDown' })
  const b = screen.getByRole('option', { name: 'Section B' })
  await waitFor(() => expect(document.activeElement).toBe(b))
  fireEvent.click(b)
  expect(screen.getByRole('heading', { name: 'Shelf B1 · RAM' })).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'B3' }))
  trigger = screen.getByRole('button', { name: 'Section: Section B' })
  fireEvent.click(trigger)
  fireEvent.click(screen.getByRole('option', { name: 'Section A' }))
  expect(screen.getByRole('heading', { name: 'Shelf A2 · Processors' })).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Section: Section A' }))
  fireEvent.click(screen.getByRole('option', { name: 'Section B' }))
  expect(screen.getByRole('heading', { name: 'Shelf B3 · Power Supplies' })).toBeTruthy()
  fireEvent.keyDown(screen.getByRole('button', { name: 'Section: Section B' }), { key: 'ArrowUp' })
  fireEvent.click(screen.getByRole('option', { name: 'Section C' }))
  const emptyShelf = within(screen.getByRole('region', { name: 'Shelf C1 · PC Cases' }))
  fireEvent.click(emptyShelf.getByRole('button', { name: 'C2' }))
  expect(screen.getByRole('region', { name: 'Shelf C2 · Cooling Systems' }).textContent).toContain('0 of 288 units. 0%')
})

it('restores saved bin contents and summaries when the application is reopened', async () => {
  const view = render(<App />)
  fireEvent.click(screen.getByRole('button', { name: 'View Shelf A1' }))
  fireEvent.click(screen.getByRole('button', { name: /A1-L2-S3, GeForce RTX 4070 Super, 0 of 24/ }))
  const dialog = within(screen.getByRole('dialog', { name: 'Add stock' }))
  fireEvent.click(dialog.getByRole('button', { name: '+5' }))
  fireEvent.click(dialog.getByRole('button', { name: 'Add 5 units' }))
  await dialog.findByRole('heading', { name: '5 units added' })
  fireEvent.click(dialog.getByRole('button', { name: 'Done' }))
  view.unmount()
  render(<App />)
  fireEvent.click(screen.getByRole('button', { name: 'View Shelf A1' }))
  const shelf = within(screen.getByRole('region', { name: 'Shelf A1 · Graphics Cards' }))
  expect(shelf.getByRole('status').textContent).toContain('191 of 288 units. 66%')
  expect(shelf.getByRole('button', { name: /A1-L2-S3, GeForce RTX 4070 Super, 5 of 24/ })).toBeTruthy()
  expect(screen.getByRole('button', { name: 'Out · 20' })).toBeTruthy()
})
