import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { AppRouter } from './AppRouter'

afterEach(() => { cleanup(); vi.useRealTimers(); window.history.replaceState(null,'','/'); vi.unstubAllGlobals() })
const open = (path='/warehouses/nyc/switch') => { window.history.replaceState(null,'',path); render(<AppRouter />) }
it('discards a list selection on Cancel and restores the current warehouse', () => {
  open()
  fireEvent.click(screen.getByRole('radio',{name:/Frankfurt Hub/}))
  fireEvent.click(screen.getByRole('button',{name:'Cancel'}))
  expect(window.location.pathname).toBe('/warehouses/nyc/dashboard')
  expect(screen.getByRole('heading',{name:'New York Central'})).toBeTruthy()
})
it('synchronizes map selection with a filtered list and confirms only once', async () => {
  vi.useFakeTimers(); open()
  fireEvent.change(screen.getByRole('textbox',{name:'Search warehouses'}),{target:{value:'Frankfurt'}})
  fireEvent.click(screen.getByRole('button',{name:'Select Tokyo Distribution Center on map'}))
  expect((screen.getByRole('textbox',{name:'Search warehouses'}) as HTMLInputElement).value).toBe('')
  expect(screen.getByRole('radio',{name:/Tokyo Distribution Center/}).getAttribute('aria-checked')).toBe('true')
  fireEvent.click(screen.getByRole('button',{name:'Switch to this warehouse'}))
  fireEvent.keyDown(document,{key:'Escape'})
  expect(window.location.pathname).toBe('/warehouses/nyc/switch')
  await act(async()=>{vi.advanceTimersByTime(500)})
  expect(window.location.pathname).toBe('/warehouses/tyo/dashboard')
  expect(screen.getByRole('heading',{name:'Tokyo Distribution Center'})).toBeTruthy()
})
it('supports keyboard selection, empty search, and resetting the map overview', () => {
  open()
  const first=screen.getByRole('radio',{name:/New York Central/})
  fireEvent.keyDown(first,{key:'End'})
  expect(screen.getByRole('radio',{name:/Riyadh Warehouse/}).getAttribute('aria-checked')).toBe('true')
  fireEvent.click(screen.getByRole('button',{name:'Show all warehouses'}))
  fireEvent.change(screen.getByRole('textbox',{name:'Search warehouses'}),{target:{value:'missing'}})
  expect(screen.getByRole('status').textContent).toContain('No warehouses match')
  fireEvent.keyDown(document,{key:'Escape'})
  expect(window.location.pathname).toBe('/warehouses/nyc/dashboard')
})
it('opens a warehouse deep link, returns to it, and handles an unknown warehouse', () => {
  open('/warehouses/fra/dashboard')
  expect(screen.getByRole('heading',{name:'Frankfurt Hub'})).toBeTruthy()
  fireEvent.click(screen.getByRole('button',{name:/Switch Warehouse/}))
  expect(window.location.pathname).toBe('/warehouses/fra/switch')
  expect(screen.getByRole('radio',{name:/Frankfurt Hub/}).getAttribute('aria-checked')).toBe('true')
  act(()=>{window.history.pushState(null,'','/warehouses/invalid/switch');window.dispatchEvent(new PopStateEvent('popstate'))})
  expect(screen.getByRole('heading',{name:'Page not found'})).toBeTruthy()
})
